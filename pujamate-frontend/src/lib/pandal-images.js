/**
 * Normalize pandal name
 *
 * Makes matching tolerant of:
 * - uppercase/lowercase
 * - extra spaces
 */
function normalizePandalName(name) {
  return String(name || '')
    .trim()
    .replace(/\s+/g, ' ')
    .toLowerCase();
}


/**
 * Normalize image value.
 *
 * Supports both:
 *
 * 1. Simple string
 *    'https://example.com/image.jpg'
 *
 * 2. Object, for backward compatibility
 *    {
 *      url: 'https://example.com/image.jpg'
 *    }
 */
function normalizeImage(image) {
  if (typeof image === 'string') {
    const url = image.trim();

    if (!url) {
      return null;
    }

    return {
      url,
    };
  }

  if (
    image &&
    typeof image === 'object' &&
    typeof image.url === 'string' &&
    image.url.trim()
  ) {
    return {
      ...image,
      url: image.url.trim(),
    };
  }

  return null;
}


/**
 * Create normalized lookup table.
 */
const NORMALIZED_PANDAL_IMAGES = Object.entries(
  PANDAL_IMAGES
).reduce((result, [name, images]) => {
  result[normalizePandalName(name)] = Array.isArray(images)
    ? images
        .map(normalizeImage)
        .filter(Boolean)
    : [];

  return result;
}, {});


/**
 * Get images for a pandal.
 *
 * Returns:
 *
 * [
 *   {
 *     url: 'https://example.com/image.jpg'
 *   }
 * ]
 */
export function getPandalImages(name) {
  const normalizedName = normalizePandalName(name);

  if (!normalizedName) {
    return [];
  }

  return (
    NORMALIZED_PANDAL_IMAGES[normalizedName] || []
  );
}


/**
 * Check whether a pandal has images.
 */
export function hasPandalImages(name) {
  return getPandalImages(name).length > 0;
}


/**
 * Small in-memory cache.
 *
 * No API.
 * No database.
 * No Cloudinary.
 */
const resolvedImageCache = new Map();


/**
 * Load pandal images.
 *
 * Kept async so existing PandalCard
 * does not need architectural changes.
 */
export async function loadPandalImages(name) {
  const normalizedName = normalizePandalName(name);

  if (!normalizedName) {
    return [];
  }

  if (resolvedImageCache.has(normalizedName)) {
    return resolvedImageCache.get(normalizedName);
  }

  const images = getPandalImages(name);

  resolvedImageCache.set(normalizedName, images);

  return images;
}


